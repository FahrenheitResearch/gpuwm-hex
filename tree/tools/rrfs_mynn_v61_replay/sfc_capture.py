"""Capture mynnsfc_driver PRE/POST from the RRFS referee of record (44c0849 strict + NULLIFY x2 + RUC ilnb=0 x2,
a128a1e8, labelled patched) on x1.2562 hrrrv5 GFS 2023-03-31 12Z, 1 process, three steps, plus observer passivity.

Cases: c1 cold start; c2 restart from c1's +36 min restart; c3 the cycled start (do_DAcycling) from that restart.
The observer is an external process; the native binary is never rebuilt. Adapted from rp-a3-physics capture-mynn.py.
"""
import hashlib, json, os, re, shutil, subprocess, sys
from pathlib import Path
import xml.etree.ElementTree as ET

# Usage: sfc_capture.py CASE LANE   with RRFS_REFEREE_BINARY (the patched referee's atmosphere_model),
# RRFS_STEP1_DECK (the x1.2562-step1 deck folder, INPUTS.json beside it) and RRFS_INIT (its case-7 init.nc).
case, lane = sys.argv[1], Path(sys.argv[2])
deck = Path(os.environ['RRFS_STEP1_DECK'])
binary = Path(os.environ['RRFS_REFEREE_BINARY'])
BINARY_SHA = 'a128a1e86806c089ffe6d65b9f5b1c0ab18d30c32cb6ee1f1885b9899ebfb400'
observer = lane/'sfc-observer/mynnsfc_driver/observer'
assert case in ('c1', 'c2', 'c3')
duration = '00:36:00'
output = lane/'captures'/case
output.mkdir(parents=True, exist_ok=False)
sha = lambda p: hashlib.sha256(Path(p).read_bytes()).hexdigest()
assert sha(binary) == BINARY_SHA
inputs = json.loads((deck/'INPUTS.json').read_text())
# init.nc was swept after its receipt; it is regenerated by the same two-NULLIFY init_atmosphere build in this lane
# (init-x1.2562/, same namelist/streams/GFS/static). Its bytes differ only in the generated file_id attribute.
INIT = Path(os.environ['RRFS_INIT'])
inputs['inputs']['init.nc'] = dict(path=str(INIT), sha256=sha(INIT), regenerated=True)
for name, item in inputs['inputs'].items():
    assert sha(item['path']) == item['sha256'], name
for name, digest in inputs['deck_files'].items():
    assert sha(deck/name) == digest, name
env = dict(os.environ, OMP_NUM_THREADS='1', OPENBLAS_NUM_THREADS='1')
runs = []
for label in ('ordinary', 'observed'):
    run = output/label
    run.mkdir()
    for name in inputs['deck_files']:
        dest = run/name; dest.parent.mkdir(parents=True, exist_ok=True); shutil.copyfile(deck/name, dest)
    for name, item in inputs['inputs'].items():
        shutil.copyfile(item['path'], run/name)
    for path in deck.iterdir():
        if path.is_symlink() and path.is_file() and not (run/path.name).exists():
            (run/path.name).symlink_to(path.resolve())
    namelist = run/'namelist.atmosphere'
    text, count = re.subn(r"(config_run_duration\s*=\s*)'[^']*'", r"\g<1>'"+duration+"'", namelist.read_text()); assert count == 1
    if case in ('c2', 'c3'):
        # c3 is the RRFS cycled start: native reads the restart stream as the background (do_restart false,
        # do_DAcycling true); a DAcycling start from init.nc alone segfaults natively (no restart.<start>.nc).
        restart = lane/'captures/c1/ordinary/restart.2023-03-31_12.36.00.nc'
        shutil.copyfile(restart, run/restart.name)
        (run/'restart_timestamp').write_text('2023-03-31_12:36:00')
        text, count = re.subn(r"(config_start_time\s*=\s*)'[^']*'", r"\g<1>'2023-03-31_12:36:00'", text); assert count == 1
    if case == 'c2':
        text, count = re.subn(r'config_do_restart\s*=\s*false', 'config_do_restart = true', text); assert count == 1
    if case == 'c3':
        text, count = re.subn(r'config_do_DAcycling\s*=\s*false', 'config_do_DAcycling = true', text); assert count == 1
    namelist.write_text(text)
    streams = run/'streams.atmosphere'
    tree = ET.parse(streams)
    for stream in tree.getroot():
        if 'output' in stream.get('type', '').split(';') and stream.get('output_interval'):
            stream.set('output_interval', duration)
    tree.write(streams)
    command = [str(binary)]
    if label == 'observed':
        command = [str(observer), *command, str(output/'captures')]
    command = ['timeout', '300', 'nice', '-n', '10', 'taskset', '-c', '8-23', *command]
    with (output/(label+'.log')).open('w') as log:
        result = subprocess.run(command, cwd=run, env=env, stdout=log, stderr=subprocess.STDOUT)
    runs.append(dict(label=label, argv=command, exit=result.returncode,
                     outputs={p.name: sha(p) for p in run.glob('*.nc') if p.name not in inputs['inputs']}))
    if result.returncode:
        raise RuntimeError(label+' exit '+str(result.returncode))

sys.path.insert(0, str(Path(__file__).resolve().parents[2]/'src'))
from hexcore.restart_v842 import _call, inspect_stream
import numpy as np
rows = []
names = [set(r['outputs']) for r in runs]
assert names[0] == names[1] and names[0]
for name in sorted(names[0]):
    if case in ('c2', 'c3') and name == 'restart.2023-03-31_12.36.00.nc':
        continue  # the copied restart input, not an output
    paths = [output/label/name for label in ('ordinary', 'observed')]
    work = output/'compare'/name; work.mkdir(parents=True, exist_ok=True)
    decoded = [_call(dict(operation='read', path=str(p), output_directory=str(work/l)), work) for p, l in zip(paths, 'ab')]
    byname = [{v['name']: v for v in d['variables']} for d in decoded]
    assert set(byname[0]) == set(byname[1])
    fields = []
    for field, var in byname[0].items():
        size = np.dtype(var['dtype']).itemsize
        data = [np.frombuffer(Path(v[field]['filename']).read_bytes(), dtype='V'+str(size)) for v in byname]
        fields.append(dict(name=field, words=len(data[0]), different=int(np.count_nonzero(data[0] != data[1]))))
    rows.append(dict(file=name, fields=fields))
    shutil.rmtree(work)
calls = [json.loads(line) for line in (output/'captures/rank0-calls.jsonl').read_text().splitlines()]
receipt = dict(schema='rrfs-44c0849-mynnsfc-capture-v1', case=case,
    referee='44c0849 strict + NULLIFY x2 + RUC ilnb=0 x2 (a128a1e8, labelled patched)',
    binary=str(binary), binary_sha256=BINARY_SHA, inputs=inputs['inputs'], observer_sha256=sha(observer), deck=str(deck),
    duration=duration, dt=720, process_count=1, runs=runs, rows=rows, calls=calls,
    words=sum(f['words'] for r in rows for f in r['fields']),
    different=sum(f['different'] for r in rows for f in r['fields']),
    captures={p.name: sha(p) for p in (output/'captures').iterdir() if p.is_file()})
(output/'capture-receipt.json').write_text(json.dumps(receipt, indent=2)+'\n')
print(json.dumps({k: receipt[k] for k in ('case', 'words', 'different')}), len(calls), 'call records')
assert receipt['different'] == 0
