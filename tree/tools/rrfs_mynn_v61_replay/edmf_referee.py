"""Standalone native MYNN-EDMF referee: one pin's MPAS driver, built CPU-only with the 44c0849 gnu-strict recipe.

A referee tool (tools/ and tests/ only, never on a run path). It builds a shared library from

- mpas_kind_types.F, mpas_constants.F (RRFS 44c0849 framework) and mpas_atmphys_constants.F (44c0849 physics);
- the MYNN-EDMF sources of one pin: ``pinned`` (c6d08709, the 44c0849 submodule, 3 files, no -Dmpas, as the
  44c0849 physics Makefile builds it) or ``v6`` (a NCAR/MYNN-EDMF v6 checkout, 4 files, -Dmpas, as the RRFS host that
  calls the unified driver builds it: ufs-community/MPAS-Model noaa/develop de016e0
  src/core_atmosphere/physics/Makefile:73-74 passes COREDEF=-Dmpas);
- a generated bind(c) bridge that calls ``mynnedmf_driver`` with every dummy by keyword, from pointers (an absent
  OPTIONAL is a disassociated pointer, which Fortran 2008 section 12.5.2, paragraph 12 makes not present);

each object compiled with the exact gfortran argv of the 44c0849 strict build (compile-commands.jsonl, the
``gfortran`` record for that object), only the source path swapped and -fPIC added for the shared library.

    python edmf_referee.py build --pin pinned --mpas <MPAS-Model> --native <44c0849 native build dir> --out <dir>
    python edmf_referee.py build --pin v6 --mynn <MYNN-EDMF checkout> --mpas <MPAS-Model> --native <...> --out <dir>
"""
from __future__ import annotations

import argparse
import ctypes as ct
import hashlib
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent.parent / 'tests' / 'rrfs_mynnedmf'))

PINNED_FILES = ('MPAS/module_bl_mynnedmf_common.F90', 'module_bl_mynnedmf.F90', 'MPAS/module_bl_mynnedmf_driver.F90')
V6_FILES = ('src/MPAS/module_bl_mynnedmf_common.F90', 'src/module_bl_mynnedmf_diags.F90',
            'src/module_bl_mynnedmf.F90', 'src/module_bl_mynnedmf_driver.F90')
SUPPORT = (('framework', 'mpas_kind_types.F'), ('framework', 'mpas_constants.F'),
           ('core_atmosphere/physics', 'mpas_atmphys_constants.F'))
FORTRAN = {'float': 'real(c_float)', 'int': 'integer(c_int)', 'double': 'real(c_double)'}


def driver_routine(paths, pin):
    import translate_module as tm
    saved = tm.MACROS
    try:
        tm.MACROS = {'mpas': 1, 'EM_CORE': None, 'HARDCODE_VERTICAL': None} if pin == 'v6' else None
        _, routines = tm.parse_modules(paths)
    finally:
        tm.MACROS = saved
    return routines['mynnedmf_driver']


def bridge_source(routine) -> str:
    """bind(c) entry: ptrs(n) (null = absent), ext(4, n) extents; every dummy passed by keyword."""
    args = [a for a in routine.arguments if a != 'errmsg']
    n = len(args)
    decl, scal, arrs, call = [], [], [], []
    for i, name in enumerate(args, 1):
        var = routine.variables[name]
        if var.dimensions:
            kind = FORTRAN[var.kind]
            rank = len(var.dimensions)
            colons = ','.join(':' * rank)
            decl.append(f'  {kind}, pointer :: t_{name}({colons}), a_{name}({colons})')
            lows = []
            for dim in var.dimensions:
                edges = dim.split(':')
                low = (edges[0] or '1') if len(edges) == 2 else '1'
                lows.append(low if low.isdecimal() else 's_' + low)
            arrs.append(f'  if (c_associated(ptrs({i}))) then\n'
                        f'    call c_f_pointer(ptrs({i}), t_{name}, ext(1:{rank},{i}))\n'
                        f'    a_{name}({",".join(lo + ":" for lo in lows)}) => t_{name}\n'
                        f'  else\n    nullify(a_{name})\n  end if')
            call.append(f'{name}=a_{name}')
        elif var.kind == 'bool':
            decl.append(f'  integer(c_int), pointer :: i_{name}\n  logical, target :: v_{name}\n'
                        f'  logical, pointer :: s_{name}')
            scal.append(f'  if (c_associated(ptrs({i}))) then\n    call c_f_pointer(ptrs({i}), i_{name})\n'
                        f'    v_{name} = i_{name} /= 0\n    s_{name} => v_{name}\n  else\n    nullify(s_{name})\n  end if')
            call.append(f'{name}=s_{name}')
        else:
            decl.append(f'  {FORTRAN[var.kind]}, pointer :: s_{name}')
            scal.append(f'  if (c_associated(ptrs({i}))) then\n    call c_f_pointer(ptrs({i}), s_{name})\n'
                        f'  else\n    nullify(s_{name})\n  end if')
            call.append(f'{name}=s_{name}')
    call.append('errmsg=errmsg')
    lines = ['! Generated by tools/rrfs_mynn_v61_replay/edmf_referee.py: a referee bridge, never on a run path.',
             'module mynn_referee_bridge', '  use iso_c_binding', '  use module_bl_mynnedmf_driver, only: mynnedmf_driver',
             '  implicit none', 'contains',
             '  subroutine mynn_referee_call(ptrs, ext, message) bind(c, name="mynn_referee_call")',
             f'  type(c_ptr), intent(in) :: ptrs({n})', f'  integer(c_int), intent(in) :: ext(4,{n})',
             '  character(kind=c_char), intent(out) :: message(256)',
             '  character(len=256) :: errmsg', '  integer :: m', *decl,
             *scal, *arrs,
             '  errmsg = " "',
             '  call mynnedmf_driver(' + ', &\n      '.join(call) + ')',
             '  do m = 1, 256', '    message(m) = errmsg(m:m)', '  end do',
             '  end subroutine mynn_referee_call', 'end module mynn_referee_bridge', '']
    return '\n'.join(lines)


def strict_argv(native: Path, filename: str) -> list[str]:
    """The gfortran argv the 44c0849 strict build used for ``filename``, without -c, source and include paths."""
    found = None
    for line in (native / 'compile-commands.jsonl').read_text().splitlines():
        row = json.loads(line)
        if row['compiler'] == 'gfortran' and filename in row['argv'] and 'build-atmosphere' in row['cwd']:
            found = row['argv']
    if found is None:
        raise RuntimeError(f'no gfortran compile record for {filename}')
    out, skip = [], False
    for token in found:
        if skip:
            skip = False
            continue
        if token in ('-c', filename):
            continue
        if token == '-o':
            skip = True
            continue
        if token.startswith('-I'):
            continue
        out.append(token)
    return out


def build(pin: str, mpas: Path, native: Path, out: Path, mynn: Path | None = None, witness_flags=(),
          source_edits=()) -> dict:
    """witness_flags: extra gfortran flags for the MYNN objects only (an undefined-read witness build, never the
    referee of record; the receipt names them)."""
    out.mkdir(parents=True, exist_ok=True)
    work = out / 'src'
    if work.exists():
        shutil.rmtree(work)
    work.mkdir()
    src = mpas / 'src'
    staged = []
    for folder, name in SUPPORT:
        shutil.copyfile(src / folder / name, work / name)
        staged.append((name, src / folder / name, strict_argv(native, name)))
    if pin == 'pinned':
        # The 44c0849 MPAS driver has "use mpas_log" with every mpas_log_write call commented out
        # (MPAS/module_bl_mynnedmf_driver.F90:4, 305-306, 666): an empty module satisfies the USE.
        (work / "mpas_log.F90").write_text("module mpas_log\nend module mpas_log\n")
        staged.append(('mpas_log.F90', None, strict_argv(native, 'module_bl_mynnedmf_driver.F90')))
        root = src / 'core_atmosphere/physics/physics_noaa/MYNN-EDMF'
        files, record = PINNED_FILES, {'module_bl_mynnedmf_common.F90': 'module_bl_mynnedmf_common.F90'}
        extra = []
    else:
        root = mynn
        files = V6_FILES
        extra = ['-Dmpas']
    for rel in files:
        name = Path(rel).name
        shutil.copyfile(root / rel, work / name)
        for edit in source_edits:
            # A labelled witness edit 'file|old|new' (exact text, once); the receipt records it.
            target, old, new = edit.split('|', 2)
            if target == name:
                text = (work / name).read_text()
                assert text.count(old) == 1, edit
                (work / name).write_text(text.replace(old, new))
        # v6 files have no 44c0849 record of their own: they take the 44c0849 line of the MYNN-EDMF object they
        # replace (the diagnostics module, new in v6, takes the core's line; all four are the same flags).
        template = name if pin == 'pinned' or name != 'module_bl_mynnedmf_diags.F90' else 'module_bl_mynnedmf.F90'
        staged.append((name, root / rel, strict_argv(native, template) + extra + list(witness_flags)))
    routine = driver_routine([work / Path(rel).name for rel in files], pin)
    (work / 'mynn_referee_bridge.F90').write_text(bridge_source(routine))
    staged.append(('mynn_referee_bridge.F90', None, strict_argv(native, 'module_bl_mynnedmf_driver.F90') + extra))
    commands = []
    for name, origin, argv in staged:
        command = ['gfortran', *argv, '-fPIC', '-c', name]
        commands.append(dict(object=name, argv=command,
                             source_sha256=hashlib.sha256((work / name).read_bytes()).hexdigest(),
                             origin=None if origin is None else str(origin)))
        subprocess.run(command, cwd=work, check=True)
    library = out / 'libmynn_referee.so'
    objects = [str(work / (Path(name).stem + '.o')) for name, _, _ in staged]
    subprocess.run(['gfortran', '-shared', '-o', str(library), *objects], check=True)
    version = subprocess.run(['gfortran', '--version'], capture_output=True, text=True).stdout.splitlines()[0]
    receipt = dict(schema='mynn-referee-build-v1', pin=pin, compiler=version, commands=commands,
                   witness_flags=list(witness_flags), source_edits=list(source_edits),
                   arguments=[dict(name=a, kind=routine.variables[a].kind, dimensions=routine.variables[a].dimensions,
                                   intent=routine.variables[a].intent, optional=routine.variables[a].optional)
                              for a in routine.arguments if a != 'errmsg'],
                   library=str(library), library_sha256=hashlib.sha256(library.read_bytes()).hexdigest(),
                   scope='CPU referee tool for module replay; never on a run path')
    (out / 'referee.json').write_text(json.dumps(receipt, indent=2) + '\n')
    return receipt


class Referee:
    """ctypes front of one built referee: call(values) runs mynnedmf_driver on host numpy arrays in place."""

    def __init__(self, directory: Path):
        import numpy as np
        self.np = np
        self.receipt = json.loads((Path(directory) / 'referee.json').read_text())
        self.lib = ct.CDLL(self.receipt['library'])
        self.lib.mynn_referee_call.argtypes = [ct.POINTER(ct.c_void_p), ct.POINTER(ct.c_int32), ct.c_char_p]
        self.arguments = self.receipt['arguments']

    def call(self, values: dict) -> dict:
        """values: name -> numpy array (Fortran order, written in place), scalar, or None (absent)."""
        np = self.np
        n = len(self.arguments)
        ptrs = (ct.c_void_p * n)()
        ext = (ct.c_int32 * (4 * n))()
        keep = []
        for i, arg in enumerate(self.arguments):
            value = values.get(arg['name'])
            if value is None:
                if not arg['optional']:
                    raise ValueError('missing non-optional argument ' + arg['name'])
                ptrs[i] = None
                continue
            if arg['dimensions']:
                dtype = {'float': np.float32, 'int': np.int32, 'double': np.float64}[arg['kind']]
                if not (isinstance(value, np.ndarray) and value.dtype == dtype and value.flags.f_contiguous
                        and value.ndim == len(arg['dimensions'])):
                    raise ValueError(f"{arg['name']} needs a Fortran-order {np.dtype(dtype)} array of rank "
                                     f"{len(arg['dimensions'])}")
                for d, extent in enumerate(value.shape):
                    ext[4 * i + d] = extent
                ptrs[i] = value.ctypes.data
            else:
                dtype = {'float': np.float32, 'int': np.int32, 'bool': np.int32, 'double': np.float64}[arg['kind']]
                box = np.array([int(value) if arg['kind'] in ('int', 'bool') else value], dtype=dtype)
                values['__box_' + arg['name']] = box
                keep.append(box)
                ptrs[i] = box.ctypes.data
        message = ct.create_string_buffer(257)
        self.lib.mynn_referee_call(ptrs, ext, message)
        out = {'errmsg': message.value.decode(errors='replace').strip()}
        if 'errflg' in values:
            out['errflg'] = int(values['__box_errflg'][0])
        return out


