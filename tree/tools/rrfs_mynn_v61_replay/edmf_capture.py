"""Capture native RRFS-MPAS 44c0849 mynnedmf_driver (or MPAS_to_physics) PRE/POST for the MYNN-EDMF v6.1.1 replay.

Three 720 s steps of x1.2562 hrrrv5 (GFS 2023-03-31 12Z, 1 process), ordinary and observed, with observer
passivity (0 different output words between them). The observer is an external process (the A3 external-ABI
observers for mynnedmf_driver and MPAS_to_physics); no native code is rebuilt. Adapted from rp-a3-physics
capture-mynn.py. Referee tool only.

Environment: MYNN_LANE (evidence/ receipts), MYNN_SCRATCH (captures), MYNN_OBSERVERS (the folder holding
mynn-observer/ and interface-observer), RRFS_REFERENCE (the 44c0849 reference: runs/x1.2562-step1, native/),
RRFS_REFEREE_BINARY (with --patched: the referee of record, 44c0849 strict + NULLIFY x2 + RUC ilnb=0 x2,
a128a1e8, labelled patched), RRFS_INIT (the case-7 init.nc regenerated by the same two-NULLIFY init build when the
published one was swept; only its file_id differs).

    edmf_capture.py --patched --stem c1p-mynn                          # C1 cold start
    edmf_capture.py --patched --boundary interface --stem c1p-interface   # its pres2_hyd_p (the v6 pint)
    --set key=value (namelist) and --file name=path (extra run file) give C2 (restart) and C3 (DA-cycled start);
    edmf_capture_chain.sh runs all six.
"""
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import xml.etree.ElementTree as ET

lane = Path(os.environ['MYNN_LANE'])
scratch = Path(os.environ['MYNN_SCRATCH'])
a3 = Path(os.environ['MYNN_OBSERVERS'])  # read-only: the A3 observers
ref = Path(os.environ['RRFS_REFERENCE'])
source = ref/'runs/x1.2562-step1'
boundary = sys.argv[sys.argv.index('--boundary')+1] if '--boundary' in sys.argv else None
stem = sys.argv[sys.argv.index('--stem')+1] if '--stem' in sys.argv else (boundary or ('mynn-hidden' if '--hidden' in sys.argv else 'mynn'))
duration = sys.argv[sys.argv.index('--duration')+1] if '--duration' in sys.argv else '00:36:00'
duration_seconds = sum(int(v)*factor for v,factor in zip(duration.split(':'),(3600,60,1)))
output = scratch/(stem+'-native-3steps')
output.mkdir(exist_ok='--compare-only' in sys.argv)
binary = ref/'native/atmosphere/atmosphere_model'
# The RRFS referee of record: 44c0849 strict + NULLIFY x2 + RUC ilnb=0 x2 (a128a1e8, labelled patched).
PATCHED = Path(os.environ.get('RRFS_REFEREE_BINARY', 'atmosphere_model'))
PATCHED_SHA = 'a128a1e86806c089ffe6d65b9f5b1c0ab18d30c32cb6ee1f1885b9899ebfb400'
if '--patched' in sys.argv:
    binary = PATCHED
observer = a3/("mynn-observer-hidden" if "--hidden" in sys.argv else "mynn-observer")/"mynnedmf_driver/observer"
if boundary:
    observer = a3/(boundary+"-observer")
if '--observer' in sys.argv:
    observer = Path(sys.argv[sys.argv.index('--observer')+1])
sha = lambda p: hashlib.sha256(p.read_bytes()).hexdigest()
write = lambda p, d: p.write_text(json.dumps(d, indent=2)+'\n')
inputs = json.loads((source/'INPUTS.json').read_text())
assert sha(binary) == (PATCHED_SHA if '--patched' in sys.argv else inputs['binary_sha256'])
# The swept init.nc is regenerated by the same native init binary and deck in lane scratch (its netCDF
# identity attributes differ, so its own hash is recorded, not the swept file's).
regenerated = Path(os.environ.get('RRFS_INIT', 'init.nc'))
if not Path(inputs['inputs']['init.nc']['path']).exists():
    inputs['inputs']['init.nc'] = dict(path=str(regenerated), sha256=sha(regenerated),
                                     regenerated_from=inputs['inputs']['init.nc'])
for name, item in inputs['inputs'].items():
    assert sha(Path(item['path'])) == item['sha256'], name
for name, digest in inputs['deck_files'].items():
    assert sha(source/name) == digest, name
env = dict(os.environ, OMP_NUM_THREADS='1', OPENBLAS_NUM_THREADS='1')
if boundary == 'external': env['RRFS_CAPTURE_FIRST_SUBSTEP_ONLY'] = '1'
if boundary == 'sw': env.update(RRFS_SW_TO_HAS_CONFIGS='1', RRFS_SW_DEGRAD_OFFSET='8f2130')
runs = json.loads((lane/'evidence'/(stem+'-native-runs.json')).read_text())['runs'] if '--compare-only' in sys.argv else []
for label in (() if '--compare-only' in sys.argv else ('ordinary', 'observed')):
    run = output/label
    run.mkdir()
    for name in inputs['deck_files']:
        dest = run/name
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source/name, dest)
    for name, item in inputs['inputs'].items():
        # DA streams can write to case ingress. Private copies avoid modifying
        # the shared native reference even if a deck later enables that path.
        shutil.copyfile(item['path'], run/name)
    tables = {}
    for path in source.iterdir():
        if path.is_symlink() and path.is_file() and not (run/path.name).exists():
            (run/path.name).symlink_to(path.resolve())
            tables[path.name] = dict(path=str(path.resolve()), sha256=sha(path))
    namelist = run/'namelist.atmosphere'
    text, count = re.subn(r"(config_run_duration\s*=\s*)'[^']*'",
                        r"\g<1>'"+duration+"'", namelist.read_text())
    assert count == 1
    if '--prate' in sys.argv:
        text,count=re.subn(r'(config_dt\s*=\s*)[0-9.]+',r'\g<1>60.',text)
        assert count==1
        text,count=re.subn(r'(calc_prate_max\s*=\s*)\.(?:false|true)\.',r'\g<1>.true.',text,flags=re.I)
        if count==0:
            text=text.replace('&physics','&physics\n calc_prate_max = .true.',1)
    for setting in [sys.argv[i + 1] for i, a in enumerate(sys.argv) if a == '--set']:
        key, value = setting.split('=', 1)
        text, count = re.subn(rf"({key}\s*=\s*)[^\n]*", lambda m: m.group(1) + value, text)
        assert count == 1, setting
    namelist.write_text(text)
    for item in [sys.argv[i + 1] for i, a in enumerate(sys.argv) if a == '--file']:
        name, origin = item.split('=', 1)
        shutil.copyfile(origin, run / name)
    streams = run/'streams.atmosphere'
    tree = ET.parse(streams)
    for stream in tree.getroot():
        if 'output' in stream.get('type', '').split(';') and stream.get('output_interval'):
            stream.set('output_interval', duration)
    tree.write(streams)
    command = [str(binary.resolve())]
    if label == 'observed':
        command = [str(observer), *command, str(output/'captures')]
    command = ['timeout', '150', 'nice', '-n', '10', 'taskset', '-c', '8-23', *command]
    with (lane/'evidence'/(stem+'-native-'+label+'.log')).open('w') as log:
        result = subprocess.run(command, cwd=run, env=env, stdout=log, stderr=subprocess.STDOUT)
    runs.append(dict(label=label, argv=command, exit=result.returncode,
                     deck={p:sha(run/p) for p in inputs['deck_files']}, tables=tables,
                     outputs={p.name:sha(p) for p in run.glob('*.nc') if p.name not in inputs['inputs']}))
    write(lane/'evidence'/(stem+'-native-runs.json'), dict(runs=runs,
        binary_sha256=sha(binary), observer_sha256=sha(observer),
        source_inputs=inputs, duration_seconds=duration_seconds, dt=60 if '--prate' in sys.argv else 720,
        init_label='two-NULLIFY derivative; confirmation pending',
        observer_environment={k:v for k,v in env.items() if k.startswith(('RRFS_CAPTURE_','RRFS_SW_'))},
        namelist_settings=[sys.argv[i + 1] for i, a in enumerate(sys.argv) if a == '--set'],
        extra_files={item.split('=', 1)[0]: dict(path=item.split('=', 1)[1], sha256=sha(Path(item.split('=', 1)[1])))
                     for item in [sys.argv[i + 1] for i, a in enumerate(sys.argv) if a == '--file']}))
    if result.returncode:
        raise RuntimeError(label+' exit '+str(result.returncode))

from hexcore.restart_v842 import _call, inspect_stream
import numpy as np
rows = []
names = [set(r['outputs']) for r in runs]
assert names[0] == names[1] and names[0]
for name in sorted(names[0]):
    paths = [output/label/name for label in ('ordinary', 'observed')]
    work = output/'compare'/name
    work.mkdir(parents=True, exist_ok=True)
    metadata = [inspect_stream(path, scratch=work) for path in paths]
    decoded = [_call(dict(operation='read', path=str(path),
        output_directory=str(work/label)), work) for path, label in zip(paths, ('a','b'))]
    byname = [{v['name']:v for v in d['variables']} for d in decoded]
    assert set(byname[0]) == set(byname[1])
    fields = []
    for field, var in byname[0].items():
        size = np.dtype(var['dtype']).itemsize
        data = [np.frombuffer(Path(v[field]['filename']).read_bytes(), dtype='V'+str(size)) for v in byname]
        assert data[0].shape == data[1].shape
        fields.append(dict(name=field, words=len(data[0]), different=int(np.count_nonzero(data[0] != data[1]))))
    file_ids = [m.get('global_attrs', {}).get('file_id') for m in metadata]
    exact_metadata = metadata[0] == metadata[1]
    for m in metadata:
        m.get('global_attrs', {}).pop('file_id', None)
    rows.append(dict(file=name, fields=fields, exact_metadata_equal=exact_metadata,
                     generated_file_ids=file_ids, metadata_except_file_id_equal=metadata[0] == metadata[1]))
if boundary:
    prefixes = sorted(p.name.removesuffix('.scope.txt') for p in (output/'captures').glob('*.scope.txt'))
    calls = [dict(prefix=p,phase=phase,call=int(p.split('.e')[1].split('.')[0]),step=None)
             for p in prefixes for phase in ('pre','post')]
else:
    calls = [json.loads(line) for line in (output/'captures/rank0-calls.jsonl').read_text().splitlines()]
pre, post = ([c for c in calls if c['phase'] == phase] for phase in ('pre','post'))
receipt = dict(schema='rrfs-44c0849-mynn-pristine-capture-v1', rows=rows, calls=calls,
    words=sum(f['words'] for r in rows for f in r['fields']),
    different=sum(f['different'] for r in rows for f in r['fields']),
    metadata_equal=all(r['exact_metadata_equal'] for r in rows),
    metadata_except_file_id_equal=all(r['metadata_except_file_id_equal'] for r in rows),
    complete_pairs=[(c['call'],c['step']) for c in pre] == [(c['call'],c['step']) for c in post],
    model_step_assignment=('radiation call step is captured xtime_s / 720 + 1' if boundary=='sw' else 'two ordered driver handoffs per step, event//2+1' if boundary in ('pbl','micro_interface') else 'first RK/substep per model step, capture ordinals0,1,2' if boundary=='external' else 'one MYNN call per step, zero-based call ordinals 0, 1, 2 map to native steps 1, 2, 3; no itimestep dummy'),
    captures={p.name:sha(p) for p in (output/'captures').iterdir() if p.is_file()},
    hidden_state_complete=False, cuda_replay_proven=False)
write(lane/'evidence'/(stem+'-native-passivity.json'), receipt)
print(json.dumps({k:receipt[k] for k in ('words','different','metadata_equal','complete_pairs')}))
assert len(pre) == (6 if boundary in ('pbl','micro_interface') else (6 if duration_seconds>2160 else 2) if boundary=='sw' else 3) and receipt['complete_pairs'] and not receipt['different'] and receipt['metadata_except_file_id_equal']
